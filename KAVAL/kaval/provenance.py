"""
KAVAL — provenance recording.

plan.md §11 rule 5: an acquired or derived file without a PROVENANCE.md entry does
not exist. This module is the only way entries get written, so the format stays
uniform and nothing slips in undocumented.
"""

import hashlib
from datetime import date
from pathlib import Path

from .config import DATA, ROOT

PROVENANCE = DATA / "PROVENANCE.md"

HEADER = """# KAVAL — Data Provenance

Every file KAVAL reads or writes is recorded here, classified as:

- `SUPPLIED` — provided by FarmwiseAI. Never redistributed; credentials never published.
- `ACQUIRED` — sourced independently from a public or permitted source.
- `DERIVED` — produced by KAVAL's own scripts from the above.

The challenge brief requires that FarmwiseAI-provided resources be clearly
distinguishable from data we sourced ourselves. This file is that distinction.

Generated by `kaval/provenance.py`. Do not edit by hand.

---
"""


def sha256(path: Path, limit_mb: int = 512) -> str:
    """Hash a file. Large files are hashed over their first `limit_mb` for speed."""
    h = hashlib.sha256()
    budget = limit_mb * 1024 * 1024
    with open(path, "rb") as fh:
        while budget > 0:
            chunk = fh.read(min(1 << 20, budget))
            if not chunk:
                break
            h.update(chunk)
            budget -= len(chunk)
    return h.hexdigest()


def _drop_entry(rel):
    """Remove any existing '### `<rel>`' block so a re-record replaces it."""
    if not PROVENANCE.exists():
        return
    lines = PROVENANCE.read_text().splitlines(keepends=True)
    out, skipping = [], False
    for line in lines:
        if line.startswith("### "):
            skipping = line.strip() == f"### `{rel}`"
        if not skipping:
            out.append(line)
    PROVENANCE.write_text("".join(out))


def _existing_block(rel):
    """Lines of the current '### `<rel>`' block, or [] if none."""
    if not PROVENANCE.exists():
        return []
    out, inside = [], False
    for line in PROVENANCE.read_text().splitlines():
        if line.startswith("### "):
            inside = line.strip() == f"### `{rel}`"
        if inside:
            out.append(line)
    return out


def record(path, *, classification, source, licence, produced_by,
           spatial_extent="Sivagiri taluk, Tenkasi district, Tamil Nadu",
           temporal_extent="n/a", crs="EPSG:4326", transform="none",
           inputs=None, notes="", agent="kaval"):
    """Append one provenance entry. Idempotent on (path, sha256)."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"cannot record provenance for missing file: {path}")

    if classification not in {"SUPPLIED", "ACQUIRED", "DERIVED"}:
        raise ValueError(f"bad classification: {classification}")
    if classification == "DERIVED" and not inputs:
        raise ValueError("DERIVED files must record their inputs")

    rel = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
    digest = sha256(path)

    if not PROVENANCE.exists():
        PROVENANCE.write_text(HEADER)

    size_mb = path.stat().st_size / 1e6
    lines = [
        f"\n### `{rel}`\n",
        f"- **Classification:** `{classification}`",
        f"- **Source:** {source}",
        f"- **Acquired/produced:** {date.today().isoformat()} by `{agent}`",
        f"- **Licence / terms:** {licence}",
        f"- **Spatial extent:** {spatial_extent}",
        f"- **Temporal extent:** {temporal_extent}",
        f"- **CRS:** {crs}",
        f"- **Transform applied:** {transform}",
        f"- **Produced by:** `{produced_by}`",
    ]
    if inputs:
        lines.append("- **Inputs:** " + ", ".join(f"`{i}`" for i in inputs))
    lines += [
        f"- **Size:** {size_mb:.1f} MB",
        f"- **SHA256:** `{digest}`",
    ]
    if notes:
        lines.append(f"- **Notes:** {notes}")

    # Idempotent on the whole entry, not just the hash: an unchanged file whose
    # recorded metadata (inputs, producer, notes) has been corrected must still be
    # re-recorded, otherwise a stale entry survives every re-run. The date line is
    # excluded from the comparison so an unchanged entry keeps its original date.
    def _body(block_lines):
        return [ln.rstrip() for ln in block_lines
                if ln.strip() and not ln.startswith("- **Acquired/produced:**")]
    if _body("\n".join(lines).splitlines()) == _body(_existing_block(rel)):
        return  # already recorded, unchanged

    # A re-run supersedes the previous entry for this path rather than appending
    # a second one — the file is a current inventory, not an append-only log.
    _drop_entry(rel)

    with open(PROVENANCE, "a") as fh:
        fh.write("\n".join(lines) + "\n")


def is_recorded(path) -> bool:
    if not PROVENANCE.exists():
        return False
    path = Path(path)
    rel = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
    return f"`{rel}`" in PROVENANCE.read_text()


def require(path):
    """Guard used by downstream phases: refuse to load an unprovenanced file."""
    if not is_recorded(path):
        raise RuntimeError(
            f"{path} has no PROVENANCE.md entry and may not be used. "
            "See plan.md §11 rule 5."
        )
    return path
